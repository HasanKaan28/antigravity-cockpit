function resolveHostLocale(vscodeInstance) {
    let configured = 'auto';
    try {
        configured = vscodeInstance.workspace.getConfiguration('antigravity.dashboard').get('language', 'auto');
    } catch {
        /* no configuration API: follow the IDE */
    }
    if (configured !== 'auto' && HOST_LOCALES[configured]) return configured;
    const ide = String((vscodeInstance && vscodeInstance.env && vscodeInstance.env.language) || 'en')
        .toLowerCase()
        .split(/[-_]/)[0];
    return HOST_LOCALES[ide] ? ide : 'en';
}

// Function replacer, so a "$" inside a path or error message is inserted as is.
function hostText(vscodeInstance, key, params = {}) {
    const template = HOST_LOCALES[resolveHostLocale(vscodeInstance)][key] || HOST_LOCALES.en[key] || key;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

