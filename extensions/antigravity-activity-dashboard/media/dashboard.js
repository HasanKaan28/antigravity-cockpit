                if (d.family && FAMILY_BY_ID[d.family]) {
                    AudioEngine.theme();
                    themeFamily = d.family;
                    applyCurrentTheme(true);
                    SpaceCanvas.color = getComputedStyle(document.documentElement).getPropertyValue('--accent').trim();
                }
                break;
