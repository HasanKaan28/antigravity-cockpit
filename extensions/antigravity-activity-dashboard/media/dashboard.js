    function formatCountdown(ms) {
        const h = Math.floor(ms / 3600000);
        const m = Math.floor((ms % 3600000) / 60000);
        const s = Math.floor((ms % 60000) / 1000);
        return `${h}h ${String(m).padStart(2, '0')}m ${String(s).padStart(2, '0')}s`;
    }

    function updateCountdowns() {
        ['gemini', 'claude'].forEach(id => {
            const el = $(id + 'TimerVal');
            if (!el) return;
            const date = resetDates[id];
            if (date && date - Date.now() > 0) {
                el.textContent = t('telemetry.resetIn', { time: formatCountdown(date - Date.now()) });
            } else if (resetLabels[id]) {
                el.textContent = t('telemetry.resetIn', { time: resetLabels[id] });
            } else {
                el.textContent = panelOnline ? t('telemetry.live') : t('telemetry.offline');
            }
        });
    }

    function setMeter(fillId, trackId, pct) {
        const fill = $(fillId);
        if (!fill) return;
        fill.classList.remove('mid', 'low', 'none');
        if (pct === null) {
            fill.classList.add('none');
            fill.style.setProperty('--pct', '0%');
        } else {
            const clamped = Math.min(100, Math.max(0, pct));
            fill.style.setProperty('--pct', clamped + '%');
            if (clamped < 20) fill.classList.add('low');
            else if (clamped < 50) fill.classList.add('mid');
        }
        const track = trackId ? $(trackId) : null;
        if (track) {
            if (pct === null) track.removeAttribute('aria-valuenow');
            else track.setAttribute('aria-valuenow', String(Math.round(pct)));
        }
    }

    function setPct(id, pct) {
        const el = $(id);
        if (!el) return;
        const html = pct === null ? '-<small>%</small>' : `${pct.toFixed(1)}<small>%</small>`;
        if (el.innerHTML !== html) {
            el.innerHTML = html;
            el.classList.remove('flash');
            void el.offsetWidth;
            el.classList.add('flash');
        }
    }

    function numberOrNull(v) {
        return (v === null || v === undefined || Number.isNaN(Number(v))) ? null : Number(v);
    }

    // Credits below this share of the monthly allowance are flagged in the quota panel.
    const LOW_CREDIT_PCT = 10;

    function creditPercent(credit) {
        const available = numberOrNull(credit.available);
        const monthly = numberOrNull(credit.monthly);
        return available !== null && monthly ? (available / monthly) * 100 : null;
    }

    function formatShare(pct) {
        return new Intl.NumberFormat(activeLocale, { maximumFractionDigits: pct < 1 ? 2 : 0 }).format(pct);
    }

    function renderPanel(panelData) {
        if (!panelData) return;
        panelOnline = panelData.status === 'ok';
        const user = panelData.user || {};
        const tier = user.tier || (panelOnline ? 'Google AI Pro' : t('telemetry.offline'));

        setText('agUserTier', tier);
        setText('modalUserTier', tier);
        setText('modalUserEmail', user.email || '-');
        setText('modalPanelStatus', t(panelOnline ? 'modal.panelConnected' : 'modal.panelOffline'));
        const dot = $('quotaStateDot');
        if (dot) dot.className = 'state-dot ' + (panelOnline ? 'ok' : 'off');

        const tokens = panelData.tokenUsage || {};
        const fmt = tokens.formatted || {};
        const prompt = tokens.promptCredits || {};
        const flow = tokens.flowCredits || {};
        const pAvail = fmt.promptAvailable ?? (prompt.available ?? '-');
        const pMonthly = fmt.promptMonthly ?? (prompt.monthly ? `${(prompt.monthly / 1000).toFixed(1)}K` : '-');
        const fAvail = fmt.flowAvailable ?? (flow.available ?? '-');
        const fMonthly = fmt.flowMonthly ?? (flow.monthly ? `${(flow.monthly / 1000).toFixed(1)}K` : '-');
        setText('teleTokenPromptVal', pAvail);
        setText('teleTokenPromptMonthly', pMonthly);
        setText('modalPromptCredits', `${pAvail} / ${pMonthly}`);
        setText('modalFlowCredits', `${fAvail} / ${fMonthly}`);

        // Derive the share from raw counts: remainingPercentage is already a percent in live data.
        const promptPct = creditPercent(prompt);
        const promptLow = promptPct !== null && promptPct < LOW_CREDIT_PCT;
        const creditLine = $('teleCredits');
        if (creditLine) {
            creditLine.classList.toggle('low', promptLow);
            if (promptLow) creditLine.title = t('telemetry.creditsLow', { pct: formatShare(promptPct) });
            else creditLine.removeAttribute('title');
        }
        const modalPrompt = $('modalPromptCredits');
        if (modalPrompt) modalPrompt.classList.toggle('low', promptLow);
        const flowPct = creditPercent(flow);
        const modalFlow = $('modalFlowCredits');
        if (modalFlow) modalFlow.classList.toggle('low', flowPct !== null && flowPct < LOW_CREDIT_PCT);

        const groups = panelData.groups || [];
        const gemini = groups.find(g => g.id === 'gemini') || {};
        const claude = groups.find(g => g.id === 'non-google' || g.id === 'claude') || {};

        const gPct = numberOrNull(gemini.remaining);
        const cPct = numberOrNull(claude.remaining);
        setMeter('geminiFill', 'geminiMeter', gPct);
        setMeter('claudeFill', 'claudeMeter', cPct);
        setPct('geminiPctVal', gPct);
        setPct('claudePctVal', cPct);

        resetDates.gemini = gemini.resetDate ? Number(gemini.resetDate) : null;
        resetDates.claude = claude.resetDate ? Number(claude.resetDate) : null;
        resetLabels.gemini = gemini.resetTime && gemini.resetTime !== '—' ? gemini.resetTime : '';
        resetLabels.claude = claude.resetTime && claude.resetTime !== '—' ? claude.resetTime : '';
        updateCountdowns();

        const weekly = gemini.weekly || {};
        const wPct = numberOrNull(weekly.remaining);
        setText('geminiWeeklyVal', wPct !== null ? `${wPct.toFixed(1)}%` : '-');
        setText('geminiWeeklyReset', weekly.resetTime ? `(${weekly.resetTime})` : '');
    }

